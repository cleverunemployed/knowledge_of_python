# Сложение (+)
a = 10 + 5      # 15
b = 3.14 + 2.5  # 5.64
c = "Hello" + " " + "World"  # Конкатенация строк: "Hello World"
d = [1, 2] + [3, 4]  # Конкатенация списков: [1, 2, 3, 4]

# Вычитание (-)
a = 10 - 5      # 5
b = 3.14 - 2.5  # 0.64
# Для множеств: разность
set1 = {1, 2, 3}
set2 = {2, 3, 4}
result = set1 - set2  # {1}

# Умножение (*)
a = 10 * 5          # 50
b = 3.14 * 2        # 6.28
c = "Hello" * 3     # "HelloHelloHello" (повтор строки)
d = [1, 2] * 3      # [1, 2, 1, 2, 1, 2] (повтор списка)

# Деление (/)
# Всегда возвращает float, даже при делении целых чисел!
a = 10 / 2      # 5.0 (float!)
b = 9 / 2       # 4.5
c = 5 / 2       # 2.5

# Целочисленное деление (//)
# Возвращает целую часть от деления
a = 10 // 3     # 3 (отбрасывает дробную часть)
b = 10 // 2.5   # 4.0 (float, потому что делили на float)
c = -10 // 3    # -4 (округляет в меньшую сторону!)

# Остаток от деления (%)
a = 10 % 3      # 1
b = 10 % 2      # 0 (проверка на четность)
c = 13.5 % 2.5  # 1.0

# Практический пример с % - проверка четности
for i in range(10):
    if i % 2 == 0:
        print(f"{i} четное")   # 0, 2, 4, 6, 8
    else:
        print(f"{i} нечетное")  # 1, 3, 5, 7, 9

# Возведение в степень (**)
a = 2 ** 3      # 8
b = 10 ** 0.5   # 3.162... (квадратный корень)
c = 2 ** -1     # 0.5
d = 16 ** (1/4) # 2.0 (корень 4-й степени)

# Унарные операции
x = 10
print(+x)   # 10 (не меняет знак)
print(-x)   # -10 (меняет знак)